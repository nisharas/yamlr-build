import pytest
import logging
logging.basicConfig(level=logging.DEBUG)
from yamlr.core.pipeline import HealingPipeline

def test_port_and_selector_alignment():
    raw_yaml = """
apiVersion: apps/v1
kind: Deployment
metadata:
  name: web-app
  namespace: prod
  labels:
    app: frontend
spec:
  template:
    spec:
      containers:
      - name: web
        image: nginx
        ports:
        - containerPort: 8080
---
apiVersion: v1
kind: Service
metadata:
  name: web-svc
  namespace: prod
spec:
  selector:
    app: frontnd  # Typo!
  ports:
  - port: 80
    targetPort: 80  # Mismatch!
"""
    # Create pipeline with minimal catalog
    catalog = {
        "apps/v1/Deployment": {},
        "v1/Service": {}
    }
    pipeline = HealingPipeline(catalog=catalog)
    
    result = pipeline.heal(raw_yaml, fix_refs=True)
    
    # Verify Selector Fix
    assert "frontend" in result.content
    assert "frontnd" not in result.content
    
    # Verify Port Fix
    print("--- HEALED CONTENT ---")
    print(result.content)
    print("--- END ---")
    assert "targetPort: 8080" in result.content
    # Use a more specific check to avoid matching 80 in 8080
    assert "targetPort: 80\n" not in result.content.replace(" ", "")
    
    print("DONE: Port and Selector Alignment verified!")

def test_ghost_resource_generation():
    raw_yaml = """
apiVersion: apps/v1
kind: Deployment
metadata:
  name: worker
spec:
  template:
    spec:
      containers:
      - name: main
        envFrom:
        - configMapRef:
            name: missing-cfg
"""
    catalog = {"apps/v1/Deployment": {}}
    pipeline = HealingPipeline(catalog=catalog)
    
    result = pipeline.heal(raw_yaml, fix_refs=True)
    
    # Verify Ghost Resource Injection
    assert "kind: ConfigMap" in result.content
    assert "name: missing-cfg" in result.content
    assert "yamlr.dev/autogenerated" in result.content
    
    print("DONE: Ghost Resource Generation verified!")

if __name__ == "__main__":
    test_port_and_selector_alignment()
    test_ghost_resource_generation()
