//! ExternalSecrets & SealedSecrets Soft-Ref Resolver (Feature 19).
//!
//! Why: Modern GitOps repositories (ArgoCD/Flux) store `ExternalSecret` or `SealedSecret`
//! instead of raw `Secret` objects. Linters produce false-positive orphan warnings.
//! This module indexes dynamically targeted secrets and auto-aligns references.

use crate::models::{NativeTelemetry, SemanticManifest, SemanticNode};
use crate::telemetry::native_record_healing_impact;

pub const SECRET_STORE_RULE_ID: &str = "REF-004";

/// Extracts target secret names defined by ExternalSecret, SealedSecret, or VaultStaticSecret.
pub fn extract_external_secret_targets(node: &SemanticNode) -> Vec<String> {
    let mut targets = Vec::new();
    let kind = node.find_value("kind").unwrap_or_default();

    match kind.as_str() {
        "ExternalSecret" => {
            if let Some(spec) = node.find_node("spec") {
                if let Some(target) = spec.find_node("target") {
                    if let Some(name) = target.find_value("name") {
                        targets.push(name.trim().to_string());
                    }
                }
            }
        }
        "SealedSecret" => {
            if let Some(meta) = node.find_node("metadata") {
                if let Some(name) = meta.find_value("name") {
                    targets.push(name.trim().to_string());
                }
            }
        }
        "VaultStaticSecret" => {
            if let Some(spec) = node.find_node("spec") {
                if let Some(dest) = spec.find_node("destination") {
                    if let Some(name) = dest.find_value("name") {
                        targets.push(name.trim().to_string());
                    }
                }
            }
        }
        _ => {}
    }

    targets
}

/// Aligns workload secret references to target secrets generated by external secret operators.
pub fn heal_secret_store_refs(
    manifest: &mut SemanticManifest,
    known_targets: &[String],
    telemetry: &mut NativeTelemetry,
) -> Vec<String> {
    let mut changes = Vec::new();
    if known_targets.is_empty() {
        return changes;
    }

    // 1. Inspect secretRef in envFrom
    for env_from in manifest.root.find_nodes_by_key_recursive_mut("envFrom") {
        for item in &mut env_from.children {
            if let Some(sec_ref) = item.find_node_mut("secretRef") {
                if let Some(name_node) = sec_ref.find_node_mut("name") {
                    let maybe_val = name_node.value.clone();
                    if let Some(current_val) = maybe_val {
                        let clean = current_val
                            .trim()
                            .trim_matches(|c| c == '\'' || c == '"')
                            .to_string();
                        if !known_targets.iter().any(|t| t == &clean) {
                            // Try fuzzy match
                            let mut best_target = None;
                            let mut best_sim = 0.0;
                            for t in known_targets {
                                let sim =
                                    crate::healers::selector_healer::similarity_ratio(&clean, t);
                                if sim >= 0.70 && sim > best_sim {
                                    best_sim = sim;
                                    best_target = Some(t);
                                }
                            }
                            if let Some(matched) = best_target {
                                let matched_str = matched.clone();
                                name_node.value = Some(matched_str.clone());
                                for s in &mut name_node.shards {
                                    s.value = Some(matched_str.clone());
                                }
                                let msg = format!(
                                    "Remediation [{}]: Aligned broken secretRef '{}' -> ExternalSecret target '{}' (similarity: {:.2}).",
                                    SECRET_STORE_RULE_ID, clean, matched_str, best_sim
                                );
                                native_record_healing_impact(telemetry, &msg);
                                changes.push(msg);
                            }
                        }
                    }
                }
            }
        }
    }

    // 2. Inspect volumes secretName
    for vols in manifest.root.find_nodes_by_key_recursive_mut("volumes") {
        for vol in &mut vols.children {
            if let Some(sec) = vol.find_node_mut("secret") {
                if let Some(sn) = sec.find_node_mut("secretName") {
                    let maybe_val = sn.value.clone();
                    if let Some(current_val) = maybe_val {
                        let clean = current_val
                            .trim()
                            .trim_matches(|c| c == '\'' || c == '"')
                            .to_string();
                        if !known_targets.iter().any(|t| t == &clean) {
                            let mut best_target = None;
                            let mut best_sim = 0.0;
                            for t in known_targets {
                                let sim =
                                    crate::healers::selector_healer::similarity_ratio(&clean, t);
                                if sim >= 0.70 && sim > best_sim {
                                    best_sim = sim;
                                    best_target = Some(t);
                                }
                            }
                            if let Some(matched) = best_target {
                                let matched_str = matched.clone();
                                sn.value = Some(matched_str.clone());
                                for s in &mut sn.shards {
                                    s.value = Some(matched_str.clone());
                                }
                                let msg = format!(
                                    "Remediation [{}]: Aligned volume secretName '{}' -> ExternalSecret target '{}' (similarity: {:.2}).",
                                    SECRET_STORE_RULE_ID, clean, matched_str, best_sim
                                );
                                native_record_healing_impact(telemetry, &msg);
                                changes.push(msg);
                            }
                        }
                    }
                }
            }
        }
    }

    changes
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_extract_external_secret_target() {
        let manifest = SemanticNode {
            key: String::new(),
            value: None,
            indent: 0,
            is_empty_flow: false,
            shards: Vec::new(),
            children: vec![
                SemanticNode {
                    key: "kind".to_string(),
                    value: Some("ExternalSecret".to_string()),
                    indent: 0,
                    is_empty_flow: false,
                    children: vec![],
                    shards: vec![],
                },
                SemanticNode {
                    key: "spec".to_string(),
                    value: None,
                    indent: 0,
                    is_empty_flow: false,
                    shards: Vec::new(),
                    children: vec![SemanticNode {
                        key: "target".to_string(),
                        value: None,
                        indent: 2,
                        is_empty_flow: false,
                        shards: Vec::new(),
                        children: vec![SemanticNode {
                            key: "name".to_string(),
                            value: Some("database-credentials".to_string()),
                            indent: 4,
                            is_empty_flow: false,
                            children: vec![],
                            shards: vec![],
                        }],
                    }],
                },
            ],
        };

        let targets = extract_external_secret_targets(&manifest);
        assert_eq!(targets, vec!["database-credentials"]);
    }

    #[test]
    fn test_align_workload_secret_ref_to_external_secret() {
        let mut telemetry = NativeTelemetry::default();
        let targets = vec!["database-credentials".to_string()];

        let mut manifest = SemanticManifest {
            root: SemanticNode {
                key: String::new(),
                value: None,
                indent: 0,
                is_empty_flow: false,
                shards: Vec::new(),
                children: vec![SemanticNode {
                    key: "envFrom".to_string(),
                    value: None,
                    indent: 0,
                    is_empty_flow: false,
                    shards: Vec::new(),
                    children: vec![SemanticNode {
                        key: "-".to_string(),
                        value: None,
                        indent: 2,
                        is_empty_flow: false,
                        shards: Vec::new(),
                        children: vec![SemanticNode {
                            key: "secretRef".to_string(),
                            value: None,
                            indent: 4,
                            is_empty_flow: false,
                            shards: Vec::new(),
                            children: vec![
                                SemanticNode {
                                    key: "name".to_string(),
                                    value: Some("database-credentals".to_string()),
                                    indent: 6,
                                    is_empty_flow: false,
                                    children: vec![],
                                    shards: vec![],
                                }, // Typo
                            ],
                        }],
                    }],
                }],
            },
            indent_step: 2,
            integrity_violations: Vec::new(),
        };

        let changes = heal_secret_store_refs(&mut manifest, &targets, &mut telemetry);
        assert_eq!(changes.len(), 1);

        let env_from = manifest.root.find_node("envFrom").unwrap();
        let sec_ref = env_from.children[0].find_node("secretRef").unwrap();
        assert_eq!(
            sec_ref.find_value("name"),
            Some("database-credentials".to_string())
        );
    }
}
